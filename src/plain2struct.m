function p = plain2struct(pplain)
%PLAIN2STRUCT Hand parameters from a 1x27 vector to a struct.
%   The order of the elements is the one used by struct2plain.
names = {'phi1_x','phi1_y','phi1_z','T1_x','T1_y','T1_z', ...
         'phiT1_x','phiT1_z','phiT2_x','phiT2_z','phiT3_z', ...
         'phiI2_x','phiI2_z','phiI3_x','phiI4_x', ...
         'phiM2_x','phiM2_z','phiM3_x','phiM4_x', ...
         'phiR2_x','phiR2_z','phiR3_x','phiR4_x', ...
         'phiL2_x','phiL2_z','phiL3_x','phiL4_x'};
for k = 1:numel(names)
    p.(names{k}) = pplain(k);
end
